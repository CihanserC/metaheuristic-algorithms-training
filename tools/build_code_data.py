"""Bundles every .py file in docs/code into docs/js/code-data.js so the site also works from file:// (no fetch needed).

Run after editing any file in docs/code:   python tools/build_code_data.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CODE_DIR = os.path.join(ROOT, 'docs', 'code')
OUT = os.path.join(ROOT, 'docs', 'js', 'code-data.js')

data = {}
for name in sorted(os.listdir(CODE_DIR)):
    if name.endswith('.py'):
        with open(os.path.join(CODE_DIR, name), encoding='utf-8') as f:
            data[name] = f.read().replace('\r\n', '\n')

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* generated by tools/build_code_data.py - do not edit */\n')
    f.write('window.MH_CODE = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')

print('bundled %d files -> %s' % (len(data), os.path.relpath(OUT, ROOT)))
